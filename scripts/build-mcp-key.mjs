// Bundles src/lib/mcp/key-server.ts into the mcp-key edge function.
import { build } from "esbuild";
import { readFileSync } from "node:fs";
const ref = process.env.VITE_SUPABASE_PROJECT_ID ?? readFileSync(".env", "utf8").match(/VITE_SUPABASE_PROJECT_ID="?([^"\n]+)/)?.[1] ?? "";
const npm = { "@lovable.dev/mcp-js": "npm:@lovable.dev/mcp-js@2.0.2", zod: "npm:zod@^3.25.76", "zod-to-json-schema": "npm:zod-to-json-schema@^3.24.0", "@supabase/supabase-js": "npm:@supabase/supabase-js@2" };
export async function buildMcpKey() {
  await build({
    stdin: { contents: 'import { handle } from "./src/lib/mcp/key-server.ts";\nDeno.serve(handle);\n', resolveDir: process.cwd(), loader: "ts" },
    bundle: true, format: "esm", platform: "neutral", outfile: "supabase/functions/mcp-key/index.ts", logLevel: "warning", define: { "import.meta.env.VITE_SUPABASE_PROJECT_ID": JSON.stringify(ref) },
    banner: { js: "// AUTO-GENERATED by scripts/build-mcp-key.mjs from src/lib/mcp – do not edit." },
    plugins: [{ name: "npm", setup(b) { b.onResolve({ filter: /^[^./]/ }, (a) => npm[a.path] ? { path: npm[a.path], external: true } : undefined); } }],
  });
}
if (import.meta.url === `file://${process.argv[1]}`) await buildMcpKey();
